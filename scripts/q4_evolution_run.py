def share_cell(point: float, draws, total_draws) -> str:
    """A share is shown only when the total trend's interval excludes zero; otherwise it has no meaning."""
    lo, _ = interval(total_draws, *INTERVAL)
    if not (np.isfinite(lo) and lo > 0):
        return "n/a (total trend interval includes 0)"
    return f"{pct(point)} {ci(100 * np.asarray(draws, float), 0)}%"


