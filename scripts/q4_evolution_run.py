def compute_all() -> Dict[str, object]:
    print(f"seed {SEED}")
    out: Dict[str, object] = {}
    out["sources"] = receipts.verify_sources()
    out["if3"] = receipts.load_if3()
    panel = receipts.load_panel()
    out["panel"] = panel
    out["panel_facts"] = receipts.check_panel(panel)
    out["panel_fp"] = receipts.panel_fingerprint(panel)
    out["score_audit"] = scores.audit(panel)
    scores.macro_score(panel, audit_table=out["score_audit"])
    pop = population.build(panel)
    dynamics.check_anchor(pop.frame, pop.anchor)
    out["pop"] = pop
    out["alternatives"] = {name: population.build(panel, name, **kw) for name, kw in population.ALTERNATIVES.items()}
    out["c3"] = auxiliary.audit(panel)

    # Bridge
    c5, c6 = bridge.load_tables()
    rows = bridge.stratify(c5, c6)
    anchors = bridge.match_anchors(rows, panel, load_c1())
    anchors["loss_reuse"] = False
    in_c5 = anchors["in_c5"]
    anchors.loc[in_c5, "loss_reuse"] = bridge.loss_reuse(anchors.loc[in_c5]).to_numpy()
    c5_keys = set((anchors.loc[in_c5, "Val_Loss"].astype(str) + "|" + anchors.loc[in_c5, "N_params_B"].astype(str)))
    s3 = ~in_c5
    s3_key = anchors.loc[s3, "Val_Loss"].astype(str) + "|" + anchors.loc[s3, "N_params_B"].astype(str)
    anchors.loc[s3, "loss_reuse"] = (s3_key.isin(c5_keys) | s3_key.duplicated(keep=False)).to_numpy()
    out["anchors"] = anchors
    out["fingerprint"] = bridge.s1_fingerprint(anchors, out["if3"])
    primary = anchors[(anchors["stratum"] == BRIDGE_PRIMARY_STRATUM) & (anchors["score_record"] == "panel_match")]
    if len(primary) != int((anchors["stratum"] == BRIDGE_PRIMARY_STRATUM).sum()):
        raise bridge.BridgeError("a primary-stratum anchor lacks a clean accepted score record")
    loss = primary["Val_Loss"].to_numpy(float)
    score = primary["panel_macro"].to_numpy(float)
    results = [bridge.leave_one_out(form, loss, score) for form in BRIDGE_FORMS]
    chosen, selection = bridge.select(results)
    out["bridge_results"], out["bridge_chosen"], out["bridge_selection"] = results, chosen, selection
    out["bridge_primary"] = primary
    s2 = anchors[anchors["stratum"] == "S2_cross_family_literature"]
    out["s2_block"] = {form: bridge.leave_one_org_out(form, s2) for form in ("constant", "linear")}
    out["s2"] = s2
    strata_counts = {k: int((anchors["stratum"] == k).sum()) for k in BRIDGE_STRATA}
    fp = out["fingerprint"]
    notes = (
        "PRIMARY STRATUM ONLY: fitted on the " + str(len(primary)) + " organizer-labelled High anchors (Pythia, "
        "same model and validation set); the Medium literature rows and the expanded C6 variant rows are carried "
        "as counts and never pooled. LOSS AXIS: the anchor losses equal the published Chinchilla law evaluated at "
        "their own (N, D) to a maximum absolute difference of " + g(float(np.max(np.abs(fp['val_loss'] - fp['published_law']))), 3)
        + ", the B1 numerical fingerprint T-008 recorded, so this axis is the Attachment-B / classic-IF3 loss scale "
        "and not an independently measured validation loss. SCORE: the anchors' macro scores lie between "
        + f(float(score.min())) + " and " + f(float(score.max())) + " on a 0-100 scale, at the floor of the "
        "benchmark. FORM: chosen by the predeclared leave-one-anchor-out rule; out-of-fold error is in "
        "prediction_error. SUPPORT: only losses within [loss_support_min, loss_support_max] may be translated; "
        "no loss-to-score slope is identified there when the chosen form is constant, and nothing may be "
        "extrapolated beyond it. Any bridge-based score must carry predictive_sd. Classic-IF3 caveat: the B1 fit "
        "supports estimator / generator recovery, not precise real-world scaling. Built by T-011; see "
        "results/tables/q4-bridge.md."
    )
    if4 = bridge.build_if4(chosen, primary, strata_counts, notes)
    path = ifc.save(if4, ensure(PROBLEM_F_INTERFACES) / IF4_FILENAME)
    out["if4_path"] = path
    out["if4_sha"] = hashlib.sha256(path.read_bytes()).hexdigest()
    out["if4_payload"] = json.loads(path.read_text(encoding="utf-8"))

    # Compute-aware subset
    csub = compute.infer_nd(compute.subset(panel, pop.anchor, set(pop.frame["model"])), out["if3"])
    out["compute_subset"] = csub
    a_only = csub[csub["stratum"] == "A"]
    out["log_compute_A"] = compute.log_compute(a_only, "log_compute:A")
    out["log_compute_all"] = compute.log_compute(csub, "log_compute:all")
    inside = csub[csub["inside_if3_box"]]
    out["if3_primary"] = compute.if3_primary(inside, out["if3"])
    out["if3_extrap"] = compute.if3_extrapolation(csub)
    out["compute_sizes"] = compute.sizes(panel, csub, len(csub))
    for key in ("log_compute_A", "log_compute_all"):
        out[key]["sizes"] = compute.sizes(panel, csub, out[key]["n"])
        compute.require_sizes(out[key])

    # Bridge-based pathway inside its support
    if4p = out["if4_payload"]
    lo, hi = if4p["params"]["loss_support_min"], if4p["params"]["loss_support_max"]
    anchors_set = set(primary["Model"])
    check = inside[~inside["model"].isin(anchors_set)].copy()
    check = check[(check["if3_loss"] >= lo) & (check["if3_loss"] <= hi)]
    payload = json.loads(receipts.read_input(receipts.IF3_FILE).read_text(encoding="utf-8"))
    ext_rel = float(payload["validation"]["B4_cross_family_excl_pythia"]["median_abs_rel_err"])
    loss_sd_ext = check["if3_loss"].to_numpy(float) * ext_rel * 1.4826
    if len(check):
        mean_b, sd_b = bridge.bridge_predict(if4p, check["if3_loss"].to_numpy(float), loss_sd_ext)
        check["bridge_mean"], check["bridge_sd"] = mean_b, sd_b
    out["bridge_check"] = check
    out["if3_ext_rel"] = ext_rel

    # Frontier, decomposition, forecast
    out["groups"] = {}
    for name in GROUPS:
        frame = pop.frame[pop.frame["group"] == name]
        comp, boot, bins, fc, framed = dynamics.forecast_table(frame, pop.anchor, "forecast:" + name)
        h, ro, feasible = dynamics.rolling_origin(framed, pop.anchor)
        out["groups"][name] = {
            "frame": framed, "comp": comp, "boot": boot, "bins": bins, "forecast": fc,
            "backtest_h": h, "backtest": ro, "feasible": feasible,
            "matched": dynamics.matched_scale(framed),
            "specs": {s: dynamics.scale_spec_residual(framed, s) for s in
                      ("linear_log10N", "quadratic_log10N", "scale_band_fixed_effects")},
            "dims": dimension_table(framed),
        }
        print(f"  group {name}: n={len(frame)} frontier trend {comp['g_time']:.3f}/yr")

    out["robust"] = robustness(out)
    return out


def dimension_table(frame: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for col, label in scores.DIMENSIONS.items():
        q = dynamics.quantile_split(frame, col)
        m = dynamics.exact_split(frame, col)
        rows.append({"dimension": label, "frontier_level": q["level0"], "frontier_trend": q["g_time"],
                     "mean_trend": m["g_time"], "mean_scale_rate": m["scale_rate"], "mean_resid_rate": m["resid_rate"]})
    return pd.DataFrame(rows)


def robustness(out: Dict[str, object]) -> Dict[str, pd.DataFrame]:
    rows = []
    for name, alt in out["alternatives"].items():
        for grp in GROUPS:
            frame = alt.frame[alt.frame["group"] == grp].copy()
            if len(frame) < MIN_FRONTIER_SET_N:
                rows.append({"population": name, "group": grp, "n": len(frame), "anchor": alt.anchor})
                continue
            frame["frontier_set"] = dynamics.frontier_flags(frame)
            comp = dynamics.components(frame)
            h12 = dynamics.years_between(dynamics.horizon_dates(alt.anchor)["primary_12m"], alt.anchor)
            rows.append({"population": name, "group": grp, "n": len(frame), "anchor": alt.anchor,
                         "level0": comp["level0"], "g_time": comp["g_time"],
                         "mean_scale_rate": comp["mean_scale_rate"], "mean_resid_rate": comp["mean_resid_rate"],
                         "fs_scale_rate": comp["frontier_scale_rate"], "fs_resid_rate": comp["frontier_resid_rate"],
                         "q_consistent": comp["q_consistent"],
                         "f12": dynamics.project(comp, h12, SCENARIOS[PRIMARY_SCENARIO])})
    pop_rows = pd.DataFrame(rows)

    strata_rows = []
    pop = out["pop"]
    for stratum in ("B", "C"):
        frame = pop.frame[pop.frame["stratum"] == stratum].copy()
        frame["frontier_set"] = dynamics.frontier_flags(frame)
        comp = dynamics.components(frame)
        h12 = dynamics.years_between(dynamics.horizon_dates(pop.anchor)["primary_12m"], pop.anchor)
        strata_rows.append({"stratum": stratum, "n": len(frame), "level0": comp["level0"], "g_time": comp["g_time"],
                            "mean_scale_rate": comp["mean_scale_rate"], "mean_resid_rate": comp["mean_resid_rate"],
                            "fs_scale_rate": comp["frontier_scale_rate"], "fs_resid_rate": comp["frontier_resid_rate"],
                            "f12": dynamics.project(comp, h12, SCENARIOS[PRIMARY_SCENARIO])})

    est_rows = []
    for grp, res in out["groups"].items():
        dense = res["bins"][~res["bins"]["sparse"]]
        row = {"group": grp, "dense_bins": len(dense), "quantile_regression": res["comp"]["g_time"]}
        for col in ("p90", "max", "top_k_mean"):
            row[col] = (float(np.polyfit(dense["t_mid"], dense[col], 1)[0]) if len(dense) >= 3 else float("nan"))
        est_rows.append(row)
    return {"population": pop_rows, "strata": pd.DataFrame(strata_rows), "estimators": pd.DataFrame(est_rows)}


