def f(x, d: int = 2) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    return f"{x:.{d}f}"


def g(x, d: int = 4) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    return f"{x:.{d}g}"


def pct(x, d: int = 1) -> str:
    return "n/a" if not np.isfinite(x) else f"{100 * x:.{d}f}%"


def ci(values, d: int = 2) -> str:
    lo, hi = interval(values, *INTERVAL)
    return f"[{f(lo, d)}, {f(hi, d)}]"


def n(x) -> str:
    return f"{int(x):,}"


def date(ts) -> str:
    return pd.Timestamp(ts).strftime("%Y-%m-%d")


def write(name: str, lines: List[str]) -> Path:
    path = ensure(TABLES) / name
    text = "\n".join(lines).rstrip("\n") + "\n"
    if "\r" in text:
        raise ValueError("generated text contains a carriage return")
    trailing = [i + 1 for i, line in enumerate(text.split("\n")) if line != line.rstrip()]
    if trailing:
        raise ValueError(name + " has trailing whitespace on line(s) " + repr(trailing[:5]))
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


