def render_robustness(o: Dict[str, object]) -> Path:
    rb = o["robust"]
    L = ["# Q4 forecast and decomposition robustness", "", GEN, "",
         "A small matrix declared in advance (`src/evolution/population.py`, `src/evolution/dynamics.py`).",
         "No specification below was chosen for its result; point estimates only.", "",
         "## Population alternatives", "",
         f"All rates in points per year. Scale / non-scale columns are the additive components (a share of a",
         f"small total is unstable, so none is shown). 12-month point under `{PRIMARY_SCENARIO}`, anchored at each",
         "alternative's own final observed date.", "",
         "| Population | Group | n | Final date | Frontier level | Frontier trend | Frontier scale-assoc. | Frontier non-scale | Mean scale-assoc. | Mean non-scale | Additive quantile consistent | 12-month point |",
         "| --- | --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | ---: |"]
    for _, r in rb["population"].iterrows():
        if "level0" not in r or not np.isfinite(r.get("level0", np.nan)):
            L.append(f"| `{r['population']}` | {r['group']} | {n(r['n'])} | {date(r['anchor'])} | too few rows | | | | | | | |")
            continue
        L.append(f"| `{r['population']}` | {r['group']} | {n(r['n'])} | {date(r['anchor'])} | {f(r['level0'])} | {f(r['g_time'])} | "
                 f"{f(r['fs_scale_rate'])} | {f(r['fs_resid_rate'])} | {f(r['mean_scale_rate'])} | {f(r['mean_resid_rate'])} | "
                 f"{'yes' if r['q_consistent'] else 'no'} | {f(r['f12'])} |")
    L += ["", "`n/a` in the frontier columns: the frontier-set split is not identified (size rule).", "",
          "## T-009 strata B and C separately (primary rules)", "",
          "| Stratum | n | Frontier level | Frontier trend | Frontier scale-assoc. | Frontier non-scale | Mean scale-assoc. | Mean non-scale | 12-month point |",
          "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for _, r in rb["strata"].iterrows():
        L.append(f"| {r['stratum']} | {n(r['n'])} | {f(r['level0'])} | {f(r['g_time'])} | {f(r['fs_scale_rate'])} | {f(r['fs_resid_rate'])} | "
                 f"{f(r['mean_scale_rate'])} | {f(r['mean_resid_rate'])} | {f(r['f12'])} |")
    L += ["", "## Frontier estimator", "",
          "Trend (pts/yr) of the frontier under each estimator: the primary quantile regression, and OLS",
          f"slopes through the non-sparse monthly P90, maximum and top-k mean (shown only with at least {MIN_ORIGINS}",
          "non-sparse months; fewer cannot support a slope).", "",
          "| Group | Non-sparse months | Quantile regression (primary) | Monthly P90 | Monthly max | Monthly top-k mean |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for _, r in rb["estimators"].iterrows():
        ok = r["dense_bins"] >= MIN_ORIGINS
        cells = [f(r[c]) if ok else "too few months" for c in ("p90", "max", "top_k_mean")]
        L.append(f"| {r['group']} | {n(r['dense_bins'])} | {f(r['quantile_regression'])} | {' | '.join(cells)} |")
    L += ["", "Scale-specification and date-source sensitivities are in `q4-decomposition.md` and in the",
          "`publication_date_only` / `fallback_date_only` rows above.", ""]
    return write("q4-forecast-robustness.md", L)


